"""Tiny original NROM program for core-launch/return tests; no battery or save RAM."""
import hashlib,json,pathlib
v=pathlib.Path(__file__).resolve().parent
prg=bytearray([0xea]*16384)
# SEI; CLD; stack; disable PPU/DMC; wait two vblanks; write universal blue;
# enable background and spin. The test core generates video only.
program=bytes.fromhex('78 d8 a2 ff 9a e8 8e 00 20 8e 01 20 8e 10 40 '
 '2c 02 20 10 fb 2c 02 20 10 fb a9 3f 8d 06 20 a9 00 8d 06 20 '
 'a9 21 8d 07 20 a9 08 8d 01 20')
spin=0x8000+len(program)
program+=bytes([0x4c,spin&255,spin>>8])
prg[:len(program)]=program
prg[-6:]=bytes.fromhex('00 80 00 80 00 80')
rom=b'NES\x1a'+bytes([1,1,0,0])+bytes(8)+prg+bytes(8192)
dest=v/'codex-video-probe.nes';dest.write_bytes(rom)
manifest=dict(file=dest.name,sha256=hashlib.sha256(rom).hexdigest(),bytes=len(rom),
 source='Original deterministic 6502 video-only test generated by create_nes_probe.py',
 mapper=0,battery=False,prg_bytes=16384,chr_bytes=8192)
(v/'codex-video-probe.json').write_text(json.dumps(manifest,indent=2))
print(json.dumps(manifest))
